#!/usr/bin/env python3
"""Render the corpus as a review sheet: corpus/review.html.

Every corpus row is shown in Tengwar (using the Alcarin Tengwar font installed
on this machine), next to its Shavian, English, IPA, glyph names and rules.

    python3 tools/render_corpus.py            # writes corpus/review.html
    python3 tools/render_corpus.py --font path/to/AlcarinTengwar-Regular.ttf

With --font the page embeds a relative URL to that file instead of relying on
an installed font.
"""

import argparse
import html
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from s2t import get_encoding, translate  # noqa: E402
from tools.corpus import CORPUS_DIR, corpus_files, load  # noqa: E402

CSS = """
:root { --bg:#fbfaf7; --fg:#1d1b17; --muted:#6b665c; --line:#ddd8cc; --chip:#ece7da; }
@media (prefers-color-scheme: dark) {
  :root { --bg:#16140f; --fg:#ece8dc; --muted:#a39e90; --line:#37332a; --chip:#2a271f; }
}
* { box-sizing: border-box; }
body { margin:0; background:var(--bg); color:var(--fg); font:16px/1.45 system-ui, sans-serif; }
main { max-width: 60rem; margin: 0 auto; padding: 1.5rem 16px 4rem; }
h1 { font-size: 1.6rem; margin: 0 0 .25rem; }
h2 { font-size: 1.25rem; margin: 2.5rem 0 .5rem; border-bottom: 1px solid var(--line); padding-bottom: .25rem; }
h3 { font-size: 1rem; margin: 1.5rem 0 .25rem; color: var(--muted); font-weight: 600; }
p.note { color: var(--muted); margin: .25rem 0 .75rem; }
.row { display: grid; grid-template-columns: minmax(0, 1.4fr) minmax(0, 1fr); gap: .25rem 1.25rem;
       padding: .6rem 0; border-top: 1px solid var(--line); align-items: center; }
.tw { font-family: "Alcarin Tengwar", "AlcarinTengwar", serif; font-size: 2.1rem; line-height: 1.9; overflow-wrap: anywhere; }
.meta { font-size: .9rem; }
.shav { font-size: 1.1rem; }
.ipa { color: var(--muted); }
code { font: .78rem/1.4 ui-monospace, monospace; color: var(--muted); overflow-wrap: anywhere; }
.chip { display:inline-block; background:var(--chip); border-radius: .6rem; padding: 0 .45rem; font-size: .75rem; margin: 0 .2rem .1rem 0; }
.pair .tw { font-size: 1.8rem; }
@media (max-width: 40rem) { .row { grid-template-columns: 1fr; } }
"""


def tengwar(enc, shavian):
    return html.escape(enc.encode(translate(shavian)))


def chips(rules):
    return "".join(f'<span class="chip">{html.escape(r)}</span>' for r in rules)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--font", help="path to a font file to reference from the page (relative to the output)")
    ap.add_argument("--encoding", default="alcarin")
    ap.add_argument("-o", "--output", default=str(CORPUS_DIR / "review.html"))
    args = ap.parse_args()
    enc = get_encoding(args.encoding)

    face = ""
    if args.font:
        rel = Path(args.font)
        face = f'@font-face {{ font-family: "Alcarin Tengwar"; src: url("{rel.as_posix()}"); }}\n'

    body = ["<h1>Corpus review sheet</h1>",
            '<p class="note">Generated by tools/render_corpus.py from corpus/*.md. '
            "If the Tengwar below shows as boxes, install the Alcarin Tengwar font or pass --font.</p>"]
    for path in corpus_files():
        cases, identities, distincts = load(path)
        title = path.read_text(encoding="utf8").split("\n", 1)[0].lstrip("# ").strip()
        body.append(f"<h2>{html.escape(title)} <small>({path.name})</small></h2>")
        last = None
        for kind, rows in (("case", cases), ("same", identities), ("distinct", distincts)):
            for r in rows:
                if r["section"] != last:
                    body.append(f"<h3>{html.escape(r['section'])}</h3>")
                    last = r["section"]
                if kind == "case":
                    body.append(
                        f'<div class="row"><div class="tw">{tengwar(enc, r["shavian"])}</div>'
                        f'<div class="meta"><div class="shav">{html.escape(r["shavian"])}</div>'
                        f'<div>{html.escape(r["english"])} <span class="ipa">{html.escape(r["ipa"])}</span></div>'
                        f'<code>{html.escape(r["glyphs"])}</code><div>{chips(r["rules"])}</div></div></div>'
                    )
                else:
                    verb = "=" if kind == "same" else "≠"
                    body.append(
                        f'<div class="row pair"><div class="tw">{tengwar(enc, r["a"])} {verb} {tengwar(enc, r["b"])}</div>'
                        f'<div class="meta"><div class="shav">{html.escape(r["a"])} {verb} {html.escape(r["b"])}</div>'
                        f'<div>{html.escape(r["note"])}</div><div>{chips(r["rules"])}</div></div></div>'
                    )
    doc = (
        "<!doctype html><html lang=en><meta charset=utf-8>"
        '<meta name=viewport content="width=device-width, initial-scale=1">'
        f"<title>Corpus review sheet</title><style>{face}{CSS}</style><main>{''.join(body)}</main></html>"
    )
    Path(args.output).write_text(doc, encoding="utf8")
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
